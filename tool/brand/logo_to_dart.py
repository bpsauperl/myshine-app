#!/usr/bin/env python3
"""Writes lib/widgets/myshine_logo_paths.dart from brand/myshine-logo.svg, so the app draws the
official logo as vectors (no image, no SVG package). Run from the repository root:
    python3 tool/brand/logo_to_dart.py
The SVG holds the outlined logo from SmileLabs' brand file (smilelabs_logos_Aug2024.ai, the
"outlined" myshine): "my" in Shine teal, "shine" in ink."""
import re

svg = open('brand/myshine-logo.svg').read()
width, height = [float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).groups()]
groups = {'my': [], 'shine': []}
for fill, d in re.findall(r'<path fill="(#[0-9a-f]{6})" d="([^"]+)"', svg):
    groups['my' if fill != '#1d1d1f' else 'shine'].append(d)
teal = next(fill for fill, _ in re.findall(r'<path fill="(#[0-9a-f]{6})" d="([^"]+)"', svg) if fill != '#1d1d1f')


def dart(d):
    out = []
    for cmd, args in re.findall(r'([MLCZ])([^MLCZ]*)', d):
        n = ', '.join(f'{float(v):.2f}'.rstrip('0').rstrip('.') for v in args.split())
        out.append({'M': f'..moveTo({n})', 'L': f'..lineTo({n})', 'C': f'..cubicTo({n})', 'Z': '..close()'}[cmd])
    return '\n    '.join(out)


lines = [
    '// GENERATED by tool/brand/logo_to_dart.py from brand/myshine-logo.svg. Do not edit by hand.',
    '// The official myShine logo, outlined, from SmileLabs\' brand file.',
    "import 'dart:ui';",
    '',
    f'const double kMyShineLogoWidth = {width:.2f};',
    f'const double kMyShineLogoHeight = {height:.2f};',
    '',
    '/// Shine teal, the colour of "my" in the logo.',
    f'const Color kMyShineLogoTeal = Color(0xFF{teal[1:].upper()});',
]
for name, paths in groups.items():
    lines += ['', f'/// The "{name}" of the logo.', f'Path myShineLogo{name.capitalize()}() => Path()', '    ' + '\n    '.join(dart(d) for d in paths) + ';']
open('lib/widgets/myshine_logo_paths.dart', 'w').write('\n'.join(lines) + '\n')
print(len(groups['my']), 'my +', len(groups['shine']), 'shine paths')
